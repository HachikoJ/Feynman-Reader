const quoteKey = (quote: Pick<CustomQuote, 'text' | 'author'>): string => `${quote.text}\u0000${quote.author}`

/**
 * Keeps the bundled system library present while preserving user-created quotes.
 * The returned array is safe to persist as user_settings.data.quotes.
 */
export function mergeDefaultQuotes(value: unknown): CustomQuote[] {
  const incoming = Array.isArray(value) ? value : []
  const system = defaultQuotesZh.map(quote => ({ ...quote }))
  const custom: CustomQuote[] = []
  const seen = new Set(system.map(quoteKey))
  for (const item of incoming) {
    if (!item || typeof item !== 'object') continue
    const quote = item as { text?: unknown; author?: unknown; isPreset?: unknown }
    if (typeof quote.text !== 'string' || typeof quote.author !== 'string') continue
    if (quote.isPreset === true) continue
    const normalized = { text: quote.text.trim(), author: quote.author.trim() || '用户摘录', isPreset: false }
    if (!normalized.text) continue
    const key = quoteKey(normalized)
    if (seen.has(key)) continue
    seen.add(key)
    custom.push(normalized)
  }
  return [...custom, ...system]
}

export function prioritizeQuotes(quotes: CustomQuote[]): CustomQuote[] {
  return [...quotes.filter(quote => !quote.isPreset), ...quotes.filter(quote => quote.isPreset)]
}

export function pickQuoteWithPriority(quotes: CustomQuote[]): CustomQuote | undefined {
  if (!quotes.length) return undefined
  const custom = quotes.filter(quote => !quote.isPreset)
  const preset = quotes.filter(quote => quote.isPreset)
  const pool = custom.length > 0 && (preset.length === 0 || Math.random() < 0.75)
    ? custom
    : (preset.length > 0 ? preset : custom)
  return pool[Math.floor(Math.random() * pool.length)] || quotes[0]
}
